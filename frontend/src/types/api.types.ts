// API Response Types
export interface ApiResponse<T> {
  success: boolean;
  data?: T;
  error?: any;
  message?: string;
}

export interface PaginatedResponse<T> {
  count: number;
  next: string | null;
  previous: string | null;
  results: T[];
}

export interface ApiError {
  detail?: string;
  message?: string;
  [key: string]: any;
}